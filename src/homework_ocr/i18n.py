# ------------------------------------------------------------------ 运行时

_current: ContextVar[str] = ContextVar("hwocr_lang", default=DEFAULT_LANG)

_PARAM = re.compile(r"\{(\w+)\}")


def normalize(lang: str | None) -> str:
    """把任何写法收敛到受支持的语言代码。"""
    if not lang:
        return DEFAULT_LANG
    tag = str(lang).strip().replace("_", "-")
    if tag in CATALOG:
        return tag
    low = tag.lower()
    for code in CATALOG:
        if code.lower() == low or code.split("-")[0].lower() == low.split("-")[0]:
            return code
    return DEFAULT_LANG


def set_current(lang: str | None) -> str:
    """设置当前请求/当前线程的语言。"""
    code = normalize(lang)
    _current.set(code)
    return code


def current() -> str:
    return _current.get()


def t(key: str, lang: str | None = None, /, **params: Any) -> str:
    """取一条译文。回退链：当前语言 -> 中文 -> key 本身。

    ``t('x', 'en')`` 显式指定语言；不指定就用当前请求的语言。
    """
    code = normalize(lang) if lang else current()
    text = CATALOG.get(code, {}).get(key)
    if text is None:
        text = CATALOG[DEFAULT_LANG].get(key)
    if text is None:
        return key
    if params:
        return _PARAM.sub(lambda m: str(params.get(m.group(1), m.group(0))), text)
    return text


def catalog(lang: str | None = None) -> dict[str, str]:
    """整份词表，给前端的 JS 用。缺词由前端再回退到 key，不会白屏。"""
    return CATALOG.get(normalize(lang) if lang else current(), CATALOG[DEFAULT_LANG])


def reason_text(code: str, lang: str | None = None, **params: Any) -> str:
    """复核原因。旧数据只有纯中文文本，这时 ``code`` 传空串，原样返回。"""
    if not code:
        return ""
    return t(f"reason.{code}", lang, **params)
